// Builds btc.browser.js: btc.js plus its @scure/@noble dependencies in one ES
// module that a web page can import without a bundler. The miner itself stays
// in cpuminer-opt-js/dist (imported relatively, so its WASM variants still load
// lazily), and so does the server-only bridge.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

export async function buildBrowser(outfile = `${ROOT}btc.browser.js`) {
  await build({
    entryPoints: [`${ROOT}btc.js`],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    external: ['./cpuminer-opt-js/dist/index.js', './cpuminer-opt-js/dist/bridge.js'],
    legalComments: 'inline',
    banner: { js: '// Generated by scripts/build-browser.mjs from btc.js and its dependencies (see AUDIT.md). Do not edit.' },
    logLevel: 'warning',
  });
  return outfile;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = await buildBrowser();
  console.log(`built ${out}`);
}
