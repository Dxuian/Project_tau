// Generates the self-contained pieces derived from the native build:
//  - src/wasm/variants/<variant>.ts: each native/out/cmo-<variant>.wasm,
//    gzip-compressed and base64-encoded, loaded lazily at runtime;
//  - src/algos.generated.ts: algorithm names and aliases, parsed from the
//    vendored miner.h / algo-gate-api.c so they always match the C build.
// Run by build-wasm.mjs after linking, and by build.mjs.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = join(ROOT, 'native/out');
const VARIANT_DIR = join(ROOT, 'src/wasm/variants');
const VENDOR = join(ROOT, 'native/vendor/cpuminer-opt');
const VARIANTS = ['sse41', 'sse42', 'avx2'];

export function embedVariants() {
  mkdirSync(VARIANT_DIR, { recursive: true });
  const built = [];
  for (const v of VARIANTS) {
    const file = join(OUT, `cmo-${v}.wasm`);
    if (!existsSync(file)) continue;
    const bytes = readFileSync(file);
    const gz = gzipSync(bytes, { level: 9 });
    const sha = createHash('sha256').update(bytes).digest('hex');
    writeFileSync(
      join(VARIANT_DIR, `${v}.ts`),
      `// Generated by scripts/embed-wasm.mjs from native/out/cmo-${v}.wasm. Do not edit.\n` +
        `export const size = ${bytes.length};\n` +
        `export const sha256 = '${sha}';\n` +
        `export const gzipBase64 = '${gz.toString('base64')}';\n`,
    );
    built.push(`${v} (${(bytes.length / 1048576).toFixed(1)} MiB -> ${(gz.length / 1048576).toFixed(1)} MiB gzip)`);
  }
  writeFileSync(
    join(VARIANT_DIR, 'index.ts'),
    `// Generated by scripts/embed-wasm.mjs. Do not edit.\n` +
      `import type { WasmVariant } from '../../types.ts';\n\n` +
      `export const BUILT_VARIANTS: WasmVariant[] = ${JSON.stringify(VARIANTS.filter((v) => existsSync(join(OUT, `cmo-${v}.wasm`))))};\n\n` +
      `export const loaders: Partial<Record<WasmVariant, () => Promise<{ gzipBase64: string; size: number }>>> = {\n` +
      VARIANTS.filter((v) => existsSync(join(OUT, `cmo-${v}.wasm`)))
        .map((v) => `  ${v}: () => import('./${v}.ts'),\n`)
        .join('') +
      `};\n`,
  );
  return built;
}

export function generateAlgoTables() {
  const minerH = readFileSync(join(VENDOR, 'miner.h'), 'utf8');
  const namesBlock = minerH.match(/static const char\* const algo_names\[\] = \{([\s\S]*?)\};/);
  if (!namesBlock) throw new Error('algo_names[] not found in miner.h');
  const names = [...namesBlock[1].matchAll(/"([^"\\]*)"|NULL/g)]
    .map((m) => (m[0] === 'NULL' ? null : m[1]))
    .filter((n) => n !== '');
  const gate = readFileSync(join(VENDOR, 'algo-gate-api.c'), 'utf8');
  const aliasBlock = gate.match(/algo_alias_map\[\]\[2\] =\s*\{([\s\S]*?)\};/);
  if (!aliasBlock) throw new Error('algo_alias_map not found in algo-gate-api.c');
  const aliases = Object.fromEntries([...aliasBlock[1].matchAll(/\{\s*"([^"]+)",\s*"([^"]+)"\s*\}/g)].map((m) => [m[1], m[2]]));
  writeFileSync(
    join(ROOT, 'src/algos.generated.ts'),
    `// Generated by scripts/embed-wasm.mjs from the vendored cpuminer-opt sources. Do not edit.\n` +
      `/** algo_names[] from miner.h; index = cpuminer-opt enum algos value. */\n` +
      `export const ALGO_NAMES: (string | null)[] = ${JSON.stringify(names)};\n\n` +
      `/** algo_alias_map from algo-gate-api.c (alias -> proper name). */\n` +
      `export const ALGO_ALIASES: Record<string, string> = ${JSON.stringify(aliases, null, 2)};\n`,
  );
  return { algos: names.length - 1, aliases: Object.keys(aliases).length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log('embedded:', embedVariants().join(', ') || '(no variants built)');
  const t = generateAlgoTables();
  console.log(`algo tables: ${t.algos} algorithms, ${t.aliases} aliases`);
}
