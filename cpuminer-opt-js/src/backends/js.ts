// Backend 'js': pure-JavaScript sha256d / sha256t / sha256q scanner, the
// fallback where WebAssembly is blocked (CSP) or has no SIMD. Works in Node,
// browsers and workers, and needs no eval.
//
// Same structure as cpuminer-opt's 4x32 code (algo/sha/sha256-hash-4way.c),
// one nonce at a time on int32 locals:
//  - per work: midstate of header bytes 0..63, rounds 0..2 and most of round 3
//    of block 1, and the nonce-independent message schedule terms X0..X6
//    (sha256Prehash);
//  - per nonce: block 1 from round 3 with zero padding words folded into the
//    round constants, sha256t / sha256q's extra passes, then the final pass
//    up to round 60 only: its e is the final hash word 7 (before the IV), so
//    nonces whose word 7 exceeds target[7] are rejected there;
//  - candidates (word 7 <= target[7]) are re-hashed in full and checked with
//    valid_hash before they become solutions.
// Fully unrolled, it does about 3.9 / 2.5 / 1.85 MH/s (sha256d / t / q) on one
// Apple Silicon core under Node 26, once the JIT has warmed up. Functions much
// larger than the two generated below lose TurboFan's fast path (measured 2x
// slower per pass), which is why the extra passes are a call.
import type { AlgoSpec, FoundSolution, Kernel, KernelSetup, ScanJob, ScanOutcome } from '../types.ts';
import { registerBackend, SHA256_FAMILY, type BackendFactory } from './registry.ts';
import {
  checkScanJob,
  makeSolution,
  MAX_SOLUTIONS,
  sha256HashNonce,
  sha256Passes,
  sha256Prehash,
  validHash,
} from './sha256-js.ts';

/** Words of the per-work block the scanner reads (see scanRange). */
const PARAM_WORDS = 24;

export class JsSha256Kernel implements Kernel {
  readonly backend = 'js' as const;
  readonly granularity = 1;
  private readonly passes: number;
  private readonly params = new Int32Array(PARAM_WORDS);
  private readonly io = new Int32Array(8);
  private readonly hash = new Uint32Array(8);

  constructor(algo: string) {
    this.passes = sha256Passes(algo);
  }

  scan(job: ScanJob): ScanOutcome {
    checkScanJob(job);
    const { data, target, start, end } = job;
    const pre = sha256Prehash(data);
    const p = this.params;
    p.set(pre.midstate, 0);
    p.set(pre.state4, 8);
    p.set(pre.x, 16);
    p[23] = target[7] ^ 0x80000000; // unsigned compare as signed
    const extra = this.passes - 2;
    const solutions: FoundSolution[] = [];
    for (let n = start; n < end; ) {
      const c = scanRange(p, n, end, extra, this.io);
      if (c < 0) break;
      if (solutions.length < MAX_SOLUTIONS) {
        const hash = sha256HashNonce(data, c, this.passes, this.hash, pre.midstate);
        if (validHash(hash, target)) solutions.push(makeSolution(job, c, hash));
      }
      n = c + 1;
    }
    return { hashesDone: end - start, solutions };
  }

  memoryBytes(): number {
    return (PARAM_WORDS + 16) * 4;
  }

  dispose(): void {}
}

export function createJsKernel(setup: KernelSetup): JsSha256Kernel {
  if (!SHA256_FAMILY.has(setup.algo.name)) throw new Error(`js backend does not implement ${setup.algo.name}`);
  return new JsSha256Kernel(setup.algo.name);
}

export const jsBackend: BackendFactory = {
  name: 'js',
  kind: 'cpu',
  priority: 50,
  unsupported(algo: AlgoSpec): string | null {
    return SHA256_FAMILY.has(algo.name) ? null : `js implements ${[...SHA256_FAMILY].join(', ')} only`;
  },
  async create(setup: KernelSetup): Promise<Kernel> {
    return createJsKernel(setup);
  },
};

registerBackend(jsBackend);

